export type Lang =
  | "en"
  | "ru"
  | "zh"
  | "hi"
  | "es"
  | "pt"
  | "ja"
  | "ko"
  | "de"
  | "fr";

/** The languages the switcher offers, each named in itself. */
export const LANGS: { id: Lang; name: string; short: string }[] = [
  { id: "en", name: "English", short: "EN" },
  { id: "ru", name: "Русский", short: "RU" },
  { id: "zh", name: "中文", short: "中文" },
  { id: "hi", name: "हिन्दी", short: "हि" },
  { id: "es", name: "Español", short: "ES" },
  { id: "pt", name: "Português", short: "PT" },
  { id: "ja", name: "日本語", short: "日本" },
  { id: "ko", name: "한국어", short: "한국" },
  { id: "de", name: "Deutsch", short: "DE" },
  { id: "fr", name: "Français", short: "FR" },
];

export function isLang(x: unknown): x is Lang {
  return typeof x === "string" && LANGS.some((l) => l.id === x);
}

/** The language a locale string names (`ru_RU.UTF-8`, `zh-Hans`, `pt-BR`), English otherwise. */
export function langFromLocale(locale: string | undefined): Lang {
  const code =
    (locale ?? "").toLowerCase().replace("-", "_").split(/[_.@]/)[0] ?? "";
  return isLang(code) ? code : "en";
}

